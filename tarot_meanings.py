def interpret_tarot_card(card: str) -> dict:
    """Validate exact card names from tarot_core.DECK and return reflection."""
    if not isinstance(card,str):
        raise ValueError("Unknown tarot card")
    if card in MAJOR:
        theme,reflection=MAJOR[card]
        family="Major Arcana"
    else:
        try: rank,suit=card.split(" of ",1)
        except ValueError as exc: raise ValueError("Unknown tarot card") from exc
        if rank not in RANKS or suit not in SUITS:
            raise ValueError("Unknown tarot card")
        rank_theme,rank_prompt=RANKS[rank]
        suit_theme,suit_domain=SUITS[suit]
        theme=f"{suit_theme} — {rank_theme}"
        reflection=f"{suit_domain}နဲ့ပတ်သက်ပြီး {rank_prompt}"
        family="Minor Arcana"
    return {"card":card,"family":family,"theme":theme,
            "reflection":reflection,"is_prediction":False,
            "method":"Original Burmese symbolic reflection based on standard 78-card tarot structure"}
